"""Sign detector accuracy on the held-out validation videos (CLAUDE.md §15, plan A).

Runs Ultralytics validation of the detector on the validation split written by
training/prepare_dognellaf.py: 3,027 frames from 119 source videos that were never used for
training (the split is by video, so near-identical frames cannot leak). Reports overall precision,
recall, mAP50 and mAP50-95 over all 89 classes, and AP per class for the signs our rules use.
Writes eval/results/detector_eval.{json,md}.

    uv run python eval/eval_detector.py --weights ~/signcoach-data/models/dognellaf_y11s_1024.pt --imgsz 1024
"""

from __future__ import annotations

import argparse
import json
import tempfile
from collections import Counter
from pathlib import Path

from app.settings import REPO_DIR, get_settings
from pipeline.detect import ClassMap
from pipeline.detection_eval import DATASET


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--weights", type=Path, required=True)
    ap.add_argument("--imgsz", type=int, default=1024)
    ap.add_argument("--model-name", default="dognellaf_y11s", help="class map used to name the catalogue signs")
    args = ap.parse_args()

    from ultralytics import YOLO

    s = get_settings()
    model = YOLO(str(args.weights.expanduser()))
    with tempfile.TemporaryDirectory() as tmp:
        m = model.val(data=str(DATASET / "data.yaml"), split="val", imgsz=args.imgsz, batch=16, device=s.device,
                      plots=False, verbose=False, project=tmp, name="val")
    names = model.names
    instances = Counter(int(line.split()[0]) for lbl in (DATASET / "labels" / "val").glob("*.txt")
                        for line in lbl.read_text().splitlines() if line.strip())
    cmap = ClassMap.for_model(args.model_name)
    per_class = []
    for i, c in enumerate(m.box.ap_class_index):
        code, value = cmap.lookup(names[int(c)])
        per_class.append({"class": names[int(c)], "sign": f"{code}/{value}" if value else code,
                          "instances": instances.get(int(c), 0), "ap50": round(float(m.box.ap50[i]), 3),
                          "ap50_95": round(float(m.box.ap[i]), 3)})
    result = {"weights": str(args.weights), "imgsz": args.imgsz, "frames": len(list((DATASET / "images" / "val").iterdir())),
              "precision": round(float(m.box.mp), 3), "recall": round(float(m.box.mr), 3),
              "map50": round(float(m.box.map50), 3), "map50_95": round(float(m.box.map), 3), "per_class": per_class}
    out = REPO_DIR / "eval" / "results"
    (out / "detector_eval.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    lines = ["# Sign detector on held-out videos", "",
             f"Generated by `eval/eval_detector.py`: `{args.weights.name}` at {args.imgsz} px on {result['frames']} frames "
             "from 119 validation videos never seen in training (split by video).", "",
             "| Precision | Recall | mAP50 | mAP50-95 |", "|---:|---:|---:|---:|",
             f"| {result['precision']} | {result['recall']} | {result['map50']} | {result['map50_95']} |", "",
             "## Signs used by the rules", "", "| Class | Sign | Instances | AP50 | AP50-95 |", "|---|---|---:|---:|---:|"]
    lines += [f"| {r['class']} | {r['sign']} | {r['instances']} | {r['ap50']} | {r['ap50_95']} |"
              for r in sorted(per_class, key=lambda r: -r["instances"]) if r["sign"]]
    (out / "detector_eval.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in result.items() if k != "per_class"}, indent=2))


if __name__ == "__main__":
    main()
