"""How accurate is the speed we estimate from the video? (CLAUDE.md §15)

Compares the pipeline's video speed with ground truth read by a person from the dashcam's
on-screen GPS speed (``speed_<clip>.csv``: t_seconds,speed_kmh — eval/ground_truth/README.md).
Reports, per clip and overall: share of moments with an estimate, mean absolute error, 90th
percentile of the absolute error, bias, and how well "standing still" is recognised. Uses the
current settings (scale_k, error model), so run it on clips NOT used by calibrate_speed.py.
Writes eval/results/speed_eval.json and speed_eval.md — the only source for speed numbers in the deck.

    uv run python eval/eval_speed.py --clip ru_02 ~/signcoach-data/datasets/own/ru_02_moscow_yaroslavka_speedOSD.mp4 \
        eval/ground_truth/speed_ru_02.csv
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from app.settings import REPO_DIR, get_settings
from pipeline.motion_eval import motion_for_video, read_truth


def evaluate(motion, truth, stop_kmh: float) -> dict:
    rows, missing = [], 0
    for t, v in truth:
        near = [m for m in motion if abs(m.t - t) <= 0.5]
        est = [m.speed_kmh for m in near if m.speed_kmh is not None]
        if not est:
            missing += 1
            continue
        rows.append((v, float(np.median(est)), any(m.stopped for m in near)))
    if not rows:
        return {"moments": len(truth), "with_estimate": 0}
    err = np.array([e - v for v, e, _ in rows])
    still = [(v < stop_kmh, s) for v, _, s in rows]
    return {
        "moments": len(truth), "with_estimate": len(rows), "coverage": round(len(rows) / len(truth), 3),
        "mae_kmh": round(float(np.mean(np.abs(err))), 1), "p90_abs_err_kmh": round(float(np.percentile(np.abs(err), 90)), 1),
        "bias_kmh": round(float(np.mean(err)), 1),
        "stops_true": sum(a for a, _ in still), "stops_found": sum(a and b for a, b in still),
        "false_stops": sum((not a) and b for a, b in still),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--clip", nargs=3, action="append", metavar=("NAME", "VIDEO", "TRUTH_CSV"), required=True)
    args = ap.parse_args()
    s = get_settings()
    results = {}
    for name, video, truth in args.clip:
        motion, _, info = motion_for_video(Path(video).expanduser(), s.cfg, s.models_dir, s.device)
        results[name] = evaluate(motion, read_truth(Path(truth)), s.cfg["stop"]["speed_kmh"]) | {"camera": info}
        print(name, results[name])
    summary = {"settings": {"scale_k": s.cfg["speed"]["scale_k"], "err_model": s.cfg["speed"]["err_model"],
                            "calibrated": s.cfg["speed"].get("calibrated", False)}, "clips": results}
    out = REPO_DIR / "eval" / "results"
    (out / "speed_eval.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    lines = ["# Video speed vs on-screen GPS speed", "", "Generated by `eval/eval_speed.py`.", "",
             "| Clip | Moments | With estimate | MAE km/h | p90 abs error | Bias | Stops found / true | False stops |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for name, r in results.items():
        if r.get("with_estimate"):
            lines.append(f"| {name} | {r['moments']} | {r['coverage']:.0%} | {r['mae_kmh']} | {r['p90_abs_err_kmh']} | "
                         f"{r['bias_kmh']:+} | {r['stops_found']}/{r['stops_true']} | {r['false_stops']} |")
    (out / "speed_eval.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
