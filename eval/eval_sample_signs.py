"""Are the signs our sample lessons show right? (team check of every shown sign)

The sample lessons show, for each sign judged to apply to our car, its name, explanation and voice
prompt, and the rules use it. The team looked at one crop per such sign and wrote down what each
sign really is (`eval/ground_truth/sample_signs.csv`, format and provenance in
`eval/ground_truth/README.md`). This script compares the current sample reports with that list: a
shown sign is right when the listed sign at the same moment (±1.5 s) has the same code and value.

It measures how often what we show is right (precision). It does not measure how many signs we
missed (recall): nobody listed every sign in these videos. Shown signs with no listed sign nearby
are reported as "not checked" (e.g. after re-seeding a sample), never counted as right.

    SIGNCOACH_INSTANCE=prod uv run python eval/eval_sample_signs.py
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from app import db
from app.settings import REPO_DIR, get_settings

RESULTS = REPO_DIR / "eval" / "results"
TRUTH = REPO_DIR / "eval" / "ground_truth" / "sample_signs.csv"


def label(code: str | None, value) -> str:
    return f"{code}{'/' + str(value) if value not in (None, '') else ''}"


def read_truth(path: Path) -> dict[str, list[dict]]:
    truth: dict[str, list[dict]] = {}
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            truth.setdefault(row["sample"], []).append(
                {"t": float(row["t_seconds"]), "sign": label(row["sign_code"], row["value"]), "notes": row["notes"]})
    return truth


def check(shown: list[dict], listed: list[dict], window_s: float) -> dict:
    """Match each shown sign to an unused listed sign within window_s, preferring the same sign."""
    unused, rows = list(listed), []
    for s in sorted(shown, key=lambda s: s["t_pass"]):
        sign = label(s["sign_code"], s["value"])
        near = [x for x in unused if abs(x["t"] - s["t_pass"]) <= window_s]
        if not near:
            rows.append({"t": round(s["t_pass"], 1), "shown": sign, "really": None, "verdict": "not checked"})
            continue
        best = min(near, key=lambda x: (x["sign"] != sign, abs(x["t"] - s["t_pass"])))
        unused.remove(best)
        rows.append({"t": round(s["t_pass"], 1), "shown": sign, "really": best["sign"], "notes": best["notes"],
                     "verdict": "right" if best["sign"] == sign else "wrong"})
    count = lambda v: sum(r["verdict"] == v for r in rows)  # noqa: E731
    return {"shown": len(rows), "right": count("right"), "wrong": count("wrong"), "not_checked": count("not checked"),
            "listed_not_shown": [{"t": x["t"], "sign": x["sign"]} for x in unused], "signs": rows}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--truth", type=Path, default=TRUTH)
    ap.add_argument("--window", type=float, default=1.5, help="seconds between a shown and a listed sign")
    args = ap.parse_args()
    s = get_settings()
    truth = read_truth(args.truth)

    results = {}
    for lesson in sorted(db.list_lessons(s.db_path, []), key=lambda l: l["label"]):
        report = json.loads((s.media_dir / lesson["id"] / "report.json").read_text(encoding="utf-8"))
        shown = [x for x in report["signs"] if x["relevant"]]
        results[lesson["label"]] = check(shown, truth.get(lesson["label"], []), args.window) | {
            "lesson_id": lesson["id"], "model": report["processing"].get("model"),
            "git_sha": report["processing"].get("git_sha")}
    total = {k: sum(r[k] for r in results.values()) for k in ("shown", "right", "wrong", "not_checked")}
    checked = total["right"] + total["wrong"]
    total["share_right"] = round(total["right"] / checked, 3) if checked else None

    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "sample_signs.json").write_text(json.dumps({"total": total, "samples": results}, indent=1),
                                               encoding="utf-8")
    lines = [
        "# Signs shown in the sample lessons: right or wrong", "",
        "Generated by `eval/eval_sample_signs.py` from the current sample reports and the team's check "
        f"(`eval/ground_truth/sample_signs.csv`); a shown sign matches a listed one within ±{args.window} s. "
        "Only signs judged to apply to our car (the ones explained, voiced and used by the rules). Precision only: "
        "signs we missed are not counted.", "",
        "| Sample | Signs shown | Right | Wrong | Not checked |", "|---|---:|---:|---:|---:|",
    ]
    for name, r in results.items():
        lines.append(f"| {name} | {r['shown']} | {r['right']} | {r['wrong']} | {r['not_checked']} |")
    share = f" ({total['share_right']:.0%} of those checked)" if checked else ""
    lines += [f"| **Total** | **{total['shown']}** | **{total['right']}**{share} | **{total['wrong']}** | "
              f"**{total['not_checked']}** |", "", "Wrong or not checked:", ""]
    for name, r in results.items():
        for x in r["signs"]:
            if x["verdict"] != "right":
                m, sec = divmod(int(x["t"]), 60)
                really = f"really {x['really']}" if x["really"] else "no sign listed nearby"
                lines.append(f"- {name}, {m}:{sec:02d} — shown {x['shown']}, {really}"
                             f"{' — ' + x['notes'] if x.get('notes') else ''}")
        for x in r["listed_not_shown"]:
            lines.append(f"- {name}, {x['t']:.1f} s — listed {x['sign']}, no longer shown")
    (RESULTS / "sample_signs.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(total)


if __name__ == "__main__":
    main()
