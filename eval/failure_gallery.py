"""Failure cases of the sign detector on the held-out validation videos (CLAUDE.md §15).

Honest failure cases are part of the judging. This finds, on the held-out frames:
- misses: labelled signs the detector did not find (largest first — the ones a driver would see),
- false alarms: confident detections where no such sign is labelled,
compares in catalogue-code space (pipeline/detection_eval.py) and saves contact sheets of tight crops
around the signs into eval/results/failure_gallery/ for the deck. Crops are pixelated wherever the
face or plate detector finds something, like every other image we publish (hard rule 4).

    uv run python eval/failure_gallery.py --weights ~/signcoach-data/models/dognellaf_y11s_1024.pt --imgsz 1024
"""

from __future__ import annotations

import argparse
from pathlib import Path

import cv2
import numpy as np

from app.settings import REPO_DIR, get_settings
from pipeline.detect import ClassMap
from pipeline.detection_eval import DATASET, ground_truth, iou, predict
from pipeline.privacy import FaceDetector, pixelate
from pipeline.vehicles import PlateDetector

TILE = 200


def crop(path: Path, box, faces: FaceDetector, plates: PlateDetector) -> np.ndarray:
    img = cv2.imread(str(path))
    H, W = img.shape[:2]
    x1, y1, x2, y2 = box[0] * W, box[1] * H, box[2] * W, box[3] * H
    side = 2.2 * max(x2 - x1, y2 - y1, 24)
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    a, b = int(max(0, cx - side / 2)), int(max(0, cy - side / 2))
    c = img[b:int(min(H, cy + side / 2)), a:int(min(W, cx + side / 2))].copy()
    pixelate(c, faces.detect(c) + [tuple(int(v) for v in o.box) for o in plates.detect(c)])
    return cv2.resize(c, (TILE, TILE))


def sheet(items, title: str, path: Path) -> None:
    tiles = []
    for img, label in items:
        t = img.copy()
        cv2.rectangle(t, (0, TILE - 26), (TILE, TILE), (0, 0, 0), -1)
        cv2.putText(t, label, (4, TILE - 8), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (255, 255, 255), 1, cv2.LINE_AA)
        tiles.append(t)
    while len(tiles) % 6:
        tiles.append(np.full((TILE, TILE, 3), 255, np.uint8))
    head = np.full((40, TILE * 6, 3), 255, np.uint8)
    cv2.putText(head, title, (8, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 0, 0), 2, cv2.LINE_AA)
    rows = [np.hstack(tiles[i:i + 6]) for i in range(0, len(tiles), 6)]
    cv2.imwrite(str(path), np.vstack([head] + rows), [cv2.IMWRITE_JPEG_QUALITY, 88])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--weights", type=Path, required=True)
    ap.add_argument("--imgsz", type=int, default=1024)
    ap.add_argument("--model-name", default="dognellaf_y11s")
    ap.add_argument("--n", type=int, default=18)
    ap.add_argument("--limit", type=int, help="only the first N frames (quick check)")
    args = ap.parse_args()
    s = get_settings()
    names = [l.strip() for l in Path("~/signcoach-data/datasets/dognellaf/classes.txt").expanduser()
             .read_text(encoding="utf-8").splitlines() if l.strip()]
    images = sorted((DATASET / "images" / "val").iterdir())[: args.limit]
    gt = ground_truth(images, names, ClassMap.for_model("dognellaf_y11s"))
    preds, _ = predict(args.model_name, args.weights.expanduser(), args.imgsz, images, s.device)
    op = s.cfg["detect"]["conf"]
    misses, false_alarms = [], []
    for img in images:
        dets = [d for d in preds.get(img.name, []) if d[1] >= op]
        for k, box in gt[img.name]:
            if not any(dk == k and iou(db, box) >= 0.5 for dk, _, db in dets):
                found = [dk for dk, _, db in dets if iou(db, box) >= 0.5]
                misses.append(((box[2] - box[0]) * (box[3] - box[1]), img, box, f"{k} -> {found[0] if found else 'missed'}"))
        for dk, p, db in dets:
            if not any(k == dk and iou(db, box) >= 0.5 for k, box in gt[img.name]):
                false_alarms.append((p, img, db, f"{dk} ({p:.2f}), not labelled"))
    misses.sort(key=lambda m: -m[0])
    false_alarms.sort(key=lambda f: -f[0])
    v = s.cfg["models"]["plates"]
    faces = FaceDetector(s.models_dir / s.cfg["models"]["faces"]["weights"], s.cfg["privacy"]["face_score_threshold"])
    plates = PlateDetector(s.models_dir / v["weights"], 640, v["conf"], s.device)
    out = REPO_DIR / "eval" / "results" / "failure_gallery"
    out.mkdir(parents=True, exist_ok=True)
    sheet([(crop(img, box, faces, plates), lbl) for _, img, box, lbl in misses[:args.n]],
          f"Largest missed or misread signs ({len(misses)} in total)", out / "misses.jpg")
    sheet([(crop(img, box, faces, plates), lbl) for _, img, box, lbl in false_alarms[:args.n]],
          f"Most confident false alarms ({len(false_alarms)} in total)", out / "false_alarms.jpg")
    (out / "README.md").write_text(
        f"# Failure gallery\n\nGenerated by `eval/failure_gallery.py` (`{args.weights.name}` at {args.imgsz} px, confidence ≥ {op}) "
        f"on {len(images)} held-out validation frames. Labels: expected -> found.\n\n"
        f"- Missed or misread signs: {len(misses)} — `misses.jpg` shows the largest {min(args.n, len(misses))}.\n"
        f"- False alarms: {len(false_alarms)} — `false_alarms.jpg` shows the most confident {min(args.n, len(false_alarms))}.\n"
        "Note: some 'false alarms' may be real signs the dataset did not label.\n", encoding="utf-8")
    print(f"misses {len(misses)}, false alarms {len(false_alarms)} -> {out}")


if __name__ == "__main__":
    main()
